// protoMapperFileData holds all data needed to render a single entity's proto mapper file.
//
// Two rendering modes are supported:
//
//  1. Subpackage mode (default, !cfg.helpersInDomain):
//     Mappers and helpers live in {domain}/pbmap/ (package "pbmap").
//     Both domain and proto types are qualified (domain.User, entpb.User).
//     Helper functions are exported (PascalCase).
//
//  2. Domain mode (cfg.helpersInDomain):
//     Mappers and helpers live flat in the domain package.
//     Domain types are bare; proto types are qualified.
//     Helper functions are unexported (camelCase).
//     Mapper functions use method-receiver style: (d *User).ToProto().
type protoMapperFileData struct {
	PkgName        string
	EntityName     string
	ListName       string
	DomainGoImport string // Go import path for the domain package (subpkg mode only)
	DomainPkgAlias string // e.g. "domain" (subpkg mode only)
	ProtoGoImport  string // Go import path for the proto package
	ProtoPkgAlias  string // e.g. "entpb"
	Imports        []string
	IDField        protoMapperField
	Fields         []protoMapperField
	EnumHelpers    []protoEnumHelper
}

// protoMapperField describes one field in the proto mapper.
type protoMapperField struct {
	StructName     string
	ProtoFieldName string
	ToProtoExpr    string
	FromProtoExpr  string
}

// protoEnumHelper holds data for generating a pair of enum conversion functions.
// ProtoType, Unspecified, and ProtoConst store bare proto identifiers WITHOUT a
// package qualifier (e.g. "UserStatus", not "entpb.UserStatus"). Templates add
// the qualifier (ProtoPkgAlias) where needed.
type protoEnumHelper struct {
	ToFuncName         string
	FromFuncName       string
	DomainType         string // bare domain type, e.g. "UserStatus"
	ProtoType          string // bare proto type, e.g. "UserStatus"
	Unspecified        string // bare sentinel, e.g. "UserStatus_USER_STATUS_UNSPECIFIED"
	DefaultDomainConst string // e.g. "UserStatusActive"
	Cases              []protoEnumCase
}

type protoEnumCase struct {
	DomainConst string // e.g. "UserStatusActive"
	ProtoConst  string // bare, e.g. "UserStatus_USER_STATUS_ACTIVE"
}

// protoMapperSubpkgTmpl generates mapper functions for a sub-package (e.g. pbmap)
// that imports both the domain and proto packages.
// Both domain and proto types are fully qualified.
// Helper functions are exported (PascalCase) and local to this package.
