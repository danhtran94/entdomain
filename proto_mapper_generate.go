// generateProtoMapperFiles generates the proto mapper files for each entity.
//
// Default (cfg.helpersInDomain=false): mapper + helpers live in {domain}/pbmap/ subpackage.
// Both domain and proto types are qualified; helper functions are exported.
//
// With WithProtoHelpersInDomain(): mapper + helpers live in the domain package.
// Domain types are bare; mapper functions use method-receiver style.
func generateProtoMapperFiles(g *gen.Graph, cfg *ProtoConfig, outDir, domainPkgPath, domainPkgName string) error {
	protoGoImport, protoPkgAlias := parseGoPackage(cfg.goPackage)
	if protoPkgAlias == "" {
		protoPkgAlias = cfg.pkgName
	}

	var mapperOutDir string
	var mapperPkgName string
	var domainGoImport string
	var tmpl *template.Template
	helpersExported := !cfg.helpersInDomain

	if cfg.helpersInDomain {
		// Legacy domain mode: flat in the domain package, method-receiver style.
		mapperOutDir = filepath.Join(outDir, domainPkgPath)
		mapperPkgName = domainPkgName
		tmpl = protoMapperDomainTmpl
	} else {
		// Default: pbmap subpackage nested under the domain directory.
		mapperOutDir = filepath.Join(outDir, domainPkgPath, "pbmap")
		mapperPkgName = "pbmap"
		tmpl = protoMapperSubpkgTmpl
		var err error
		domainGoImport, err = resolveGoImportPath(g, domainPkgPath)
		if err != nil {
			return fmt.Errorf("entdomain proto mapper: resolve domain import path: %w", err)
		}
	}

	if err := os.MkdirAll(mapperOutDir, 0755); err != nil {
		return fmt.Errorf("entdomain proto mapper: create output dir: %w", err)
	}

	hasHelpers := false

	for _, t := range g.Nodes {
		ant, err := extractEntityAnnotation(t.Annotations)
		if err != nil {
			return fmt.Errorf("entdomain proto mapper: extract annotation for %s: %w", t.Name, err)
		}
		if ant == nil {
			continue
		}

		data, needsHelpers, buildErr := buildProtoMapperFileData(
			t, ant,
			mapperPkgName, protoGoImport, protoPkgAlias,
			domainGoImport, domainPkgName,
			helpersExported,
		)
		if buildErr != nil {
			return fmt.Errorf("entdomain proto mapper: build data for %s: %w", t.Name, buildErr)
		}
		if needsHelpers {
			hasHelpers = true
		}

		src, renderErr := renderProtoMapperFile(data, tmpl)
		if renderErr != nil {
			return fmt.Errorf("entdomain proto mapper: render file for %s: %w", t.Name, renderErr)
		}

		outPath := filepath.Join(mapperOutDir, strings.ToLower(t.Name)+"_proto_gen.go")
		if err := os.WriteFile(outPath, src, 0644); err != nil {
			return fmt.Errorf("entdomain proto mapper: write file %s: %w", outPath, err)
		}
	}

	if hasHelpers {
		if err := generateProtoHelpersFile(mapperOutDir, mapperPkgName, helpersExported); err != nil {
			return fmt.Errorf("entdomain proto mapper: generate helpers: %w", err)
		}
	}

	return nil
}

// buildProtoMapperFileData constructs the template data for a single entity's proto mapper file.
// helpersExported controls whether helper function calls use PascalCase (true, subpkg mode)
// or camelCase (false, domain mode).
func buildProtoMapperFileData(
	t *gen.Type, ant *EntityAnnotation,
	pkgName, protoGoImport, protoPkgAlias string,
	domainGoImport, domainPkgAlias string,
	helpersExported bool,
) (*protoMapperFileData, bool, error) {
	needsHelpers := false
	goImports := map[string]bool{}

	data := &protoMapperFileData{
		PkgName:        pkgName,
		EntityName:     t.Name,
		ListName:       t.Name + "List",
		DomainGoImport: domainGoImport,
		DomainPkgAlias: domainPkgAlias,
		ProtoGoImport:  protoGoImport,
		ProtoPkgAlias:  protoPkgAlias,
	}

	// ID field.
	idSpec := resolveEntFieldProtoSpec(t.Name, t.ID, nil)
	rawIDTo := applyExprTemplate(idSpec.ToProtoExpr, "d.ID")
	rawIDFrom := applyExprTemplate(idSpec.FromProtoExpr, "p.Id")
	trackExprImports(rawIDTo, rawIDFrom, goImports)
	if isHelperExpr(rawIDTo) || isHelperExpr(rawIDFrom) {
		needsHelpers = true
	}
	data.IDField = protoMapperField{
		StructName:     "ID",
		ProtoFieldName: "Id",
		ToProtoExpr:    adjustHelperExpr(rawIDTo, helpersExported),
		FromProtoExpr:  adjustHelperExpr(rawIDFrom, helpersExported),
	}

	// Regular fields.
	for _, f := range t.Fields {
		if f.IsEdgeField() {
			continue
		}
		fa, err := extractFieldAnnotation(f.Annotations)
		if err != nil {
			return nil, false, fmt.Errorf("extract field annotation for %s: %w", f.Name, err)
		}
		if fa != nil && fa.SkipProto {
			continue
		}

		spec := resolveEntFieldProtoSpec(t.Name, f, fa)
		if spec.IsExcluded {
			continue
		}

		protoGoName := protoPascal(f.Name)
		domainExpr := "d." + f.StructField()
		protoExpr := "p." + protoGoName

		mf := protoMapperField{
			StructName:     f.StructField(),
			ProtoFieldName: protoGoName,
		}

		if spec.IsEnum {
			toHelperName := strings.ToLower(t.Name[:1]) + t.Name[1:] + pascal(f.Name) + "ToProto"
			fromHelperName := strings.ToLower(t.Name[:1]) + t.Name[1:] + pascal(f.Name) + "FromProto"
			mf.ToProtoExpr = toHelperName + "(" + domainExpr + ")"
			mf.FromProtoExpr = fromHelperName + "(" + protoExpr + ")"

			// Enum helper: store bare proto identifiers (no package qualifier).
			prefix := strings.ToUpper(snake(t.Name)) + "_" + strings.ToUpper(snake(f.StructField()))
			enumType := t.Name + f.StructField()
			helper := protoEnumHelper{
				ToFuncName:   toHelperName,
				FromFuncName: fromHelperName,
				DomainType:   enumType,
				ProtoType:    enumType,
				Unspecified:  enumType + "_" + prefix + "_UNSPECIFIED",
			}
			defaultSet := false
			for _, v := range f.Enums {
				domainConst := enumType + pascal(v.Value)
				protoConst := enumType + "_" + prefix + "_" + strings.ToUpper(snake(v.Value))
				helper.Cases = append(helper.Cases, protoEnumCase{
					DomainConst: domainConst,
					ProtoConst:  protoConst,
				})
				if !defaultSet {
					helper.DefaultDomainConst = domainConst
					defaultSet = true
				}
			}
			data.EnumHelpers = append(data.EnumHelpers, helper)
		} else {
			rawTo := applyExprTemplate(spec.ToProtoExpr, domainExpr)
			rawFrom := applyExprTemplate(spec.FromProtoExpr, protoExpr)
			trackExprImports(rawTo, rawFrom, goImports)
			if isHelperExpr(rawTo) || isHelperExpr(rawFrom) {
				needsHelpers = true
			}
			mf.ToProtoExpr = adjustHelperExpr(rawTo, helpersExported)
			mf.FromProtoExpr = adjustHelperExpr(rawFrom, helpersExported)
		}

		data.Fields = append(data.Fields, mf)
	}

	// Edge fields.
	for _, e := range t.Edges {
		ea, err := extractEdgeAnnotation(e.Annotations)
		if err != nil {
			return nil, false, fmt.Errorf("extract edge annotation for %s: %w", e.Name, err)
		}
		if ea == nil {
			continue
		}
		fa, err := extractFieldAnnotation(e.Annotations)
		if err != nil {
			return nil, false, fmt.Errorf("extract field annotation for edge %s: %w", e.Name, err)
		}

		specs := resolveEdgeProtoSpec(e, ea, fa)
		specIdx := 0

		if ea.HasIDs() && specIdx < len(specs) {
			spec := specs[specIdx]
			specIdx++
			if !spec.IsExcluded {
				var domainFieldName, protoFieldName string
				if e.Unique {
					domainFieldName = pascal(e.Name) + "ID"
					protoFieldName = pascal(e.Name) + "Id"
				} else {
					domainFieldName = singular(pascal(e.Name)) + "IDs"
					protoFieldName = pascal(singular(e.Name)) + "Ids"
				}

				domainExpr := "d." + domainFieldName
				protoExpr := "p." + protoFieldName

				rawTo := applyExprTemplate(spec.ToProtoExpr, domainExpr)
				rawFrom := applyExprTemplate(spec.FromProtoExpr, protoExpr)

				mf := protoMapperField{
					StructName:     domainFieldName,
					ProtoFieldName: protoFieldName,
					ToProtoExpr:    adjustHelperExpr(rawTo, helpersExported),
					FromProtoExpr:  adjustHelperExpr(rawFrom, helpersExported),
				}

				if spec.IsRepeated && spec.ProtoType == "int64" {
					rawTo = "toInt64Slice(" + domainExpr + ")"
					rawFrom = "fromInt64Slice(" + protoExpr + ")"
					mf.ToProtoExpr = adjustHelperExpr(rawTo, helpersExported)
					mf.FromProtoExpr = adjustHelperExpr(rawFrom, helpersExported)
					needsHelpers = true
				}

				// Track imports and helpers from raw (pre-capitalization) expressions.
				trackExprImports(rawTo, rawFrom, goImports)
				if isHelperExpr(rawTo) || isHelperExpr(rawFrom) {
					needsHelpers = true
				}

				data.Fields = append(data.Fields, mf)
			}
		}

		if ea.HasNest() && specIdx < len(specs) {
			spec := specs[specIdx]
			specIdx++
			if !spec.IsExcluded {
				entityName := spec.NestEntityName
				domainFieldName := pascal(e.Name)
				protoFieldName := protoPascal(e.Name)
				domainExpr := "d." + domainFieldName
				protoExpr := "p." + protoFieldName

				var rawTo, rawFrom string
				if spec.IsRepeated {
					if helpersExported {
						// Subpackage mode: standalone functions in same pbmap package.
						rawTo = entityName + "ListToProto(" + domainExpr + ")"
						rawFrom = entityName + "ListFromProto(" + protoExpr + ")"
					} else {
						// Domain mode: slice has ToProto() method; FromProto is standalone.
						rawTo = domainExpr + ".ToProto()"
						rawFrom = entityName + "ListFromProto(" + protoExpr + ")"
					}
				} else {
					if helpersExported {
						rawTo = entityName + "ToProto(" + domainExpr + ")"
						rawFrom = entityName + "FromProto(" + protoExpr + ")"
					} else {
						rawTo = domainExpr + ".ToProto()"
						rawFrom = entityName + "FromProto(" + protoExpr + ")"
					}
				}

				data.Fields = append(data.Fields, protoMapperField{
					StructName:     domainFieldName,
					ProtoFieldName: protoFieldName,
					ToProtoExpr:    rawTo,
					FromProtoExpr:  rawFrom,
				})
			}
		}
	}

	// Virtual fields.
	for _, vf := range ant.VirtualFields {
		spec := resolveVirtualFieldProtoSpec(vf)
		if spec.IsExcluded {
			continue
		}

		protoGoName := protoPascal(vf.Name)
		domainExpr := "d." + pascal(vf.Name)
		protoExpr := "p." + protoGoName

		rawTo := applyExprTemplate(spec.ToProtoExpr, domainExpr)
		rawFrom := applyExprTemplate(spec.FromProtoExpr, protoExpr)
		trackExprImports(rawTo, rawFrom, goImports)
		if isHelperExpr(rawTo) || isHelperExpr(rawFrom) {
			needsHelpers = true
		}

		data.Fields = append(data.Fields, protoMapperField{
			StructName:     pascal(vf.Name),
			ProtoFieldName: protoGoName,
			ToProtoExpr:    adjustHelperExpr(rawTo, helpersExported),
			FromProtoExpr:  adjustHelperExpr(rawFrom, helpersExported),
		})
	}

	for imp := range goImports {
		data.Imports = append(data.Imports, imp)
	}
	sort.Strings(data.Imports)

	return data, needsHelpers, nil
}

// generateProtoHelpersFile writes proto_helpers_gen.go to outDir.
// When exported is true the functions have PascalCase names.
func generateProtoHelpersFile(outDir string, pkgName string, exported bool) error {
	if err := os.MkdirAll(outDir, 0755); err != nil {
		return fmt.Errorf("create helpers dir: %w", err)
	}
	var buf bytes.Buffer
	if err := protoHelpersTmpl.Execute(&buf, protoHelpersData{PkgName: pkgName, Exported: exported}); err != nil {
		return fmt.Errorf("execute helpers template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return fmt.Errorf("format helpers source (raw: %s): %w", buf.String(), err)
	}
	return os.WriteFile(filepath.Join(outDir, "proto_helpers_gen.go"), src, 0644)
}

// renderProtoMapperFile renders the given proto mapper template and gofmts the result.
func renderProtoMapperFile(data *protoMapperFileData, tmpl *template.Template) ([]byte, error) {
	var buf bytes.Buffer
	if err := tmpl.Execute(&buf, data); err != nil {
		return nil, fmt.Errorf("execute proto mapper template: %w", err)
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format proto mapper source for %s (raw:\n%s\n): %w", data.EntityName, buf.String(), err)
	}
	return src, nil
}

// applyExprTemplate substitutes %s in the format template with value.
// If template is empty, returns value directly.
func applyExprTemplate(tmpl, value string) string {
	if tmpl == "" {
		return value
	}
	return fmt.Sprintf(tmpl, value)
}

// isHelperExpr reports whether expr begins with a call to a known proto helper function.
func isHelperExpr(expr string) bool {
	for _, name := range protoHelperFuncNames {
		if strings.HasPrefix(expr, name+"(") {
			return true
		}
	}
	return false
}

// adjustHelperExpr capitalizes the first letter of a known helper function call
// when capitalize is true (helpers are exported). E.g.:
//
//	"toInt64Ptr(d.Score)" → "ToInt64Ptr(d.Score)" when capitalize=true
func adjustHelperExpr(expr string, capitalize bool) string {
	if !capitalize || expr == "" {
		return expr
	}
	for _, name := range protoHelperFuncNames {
		if strings.HasPrefix(expr, name+"(") {
			return strings.ToUpper(name[:1]) + expr[1:]
		}
	}
	return expr
}

// trackExprImports inspects a ToProto/FromProto expression pair and records
// any Go package imports they require into goImports.
func trackExprImports(rawTo, rawFrom string, goImports map[string]bool) {
	for _, expr := range [2]string{rawTo, rawFrom} {
		if strings.Contains(expr, "timestamppb") {
			goImports["google.golang.org/protobuf/types/known/timestamppb"] = true
		}
		if strings.Contains(expr, "durationpb") {
			goImports["google.golang.org/protobuf/types/known/durationpb"] = true
		}
		if strings.Contains(expr, "uuid.MustParse") || strings.Contains(expr, "uuid.UUID") {
			goImports["github.com/google/uuid"] = true
		}
		if strings.Contains(expr, "structpb") {
			goImports["google.golang.org/protobuf/types/known/structpb"] = true
		}
	}
}

// protoPascal converts a snake_case field name to the Go struct field name as
// generated by protoc-gen-go. Unlike ent's pascal(), it does NOT treat "id" as
// an acronym: "external_id" → "ExternalId" (not "ExternalID").
func protoPascal(s string) string {
	parts := strings.Split(s, "_")
	for i, p := range parts {
		if len(p) > 0 {
			parts[i] = strings.ToUpper(p[:1]) + p[1:]
		}
	}
	return strings.Join(parts, "")
}

// parseGoPackage splits "import/path;alias" into import path and alias.
func parseGoPackage(goPackage string) (importPath, alias string) {
	parts := strings.SplitN(goPackage, ";", 2)
	importPath = parts[0]
	if len(parts) == 2 {
		alias = parts[1]
	}
	return
}

// resolveGoImportPath derives the Go import path for a package whose filesystem
// location is relPkgPath relative to moduleRoot(g) (i.e. filepath.Dir(g.Config.Target)).
// It walks up from the ent target directory to find go.mod.
func resolveGoImportPath(g *gen.Graph, relPkgPath string) (string, error) {
	outDir := moduleRoot(g)
	pkgAbsPath := filepath.Join(outDir, relPkgPath)

	dir := outDir
	for {
		data, err := os.ReadFile(filepath.Join(dir, "go.mod"))
		if err == nil {
			for line := range strings.SplitSeq(string(data), "\n") {
				line = strings.TrimSpace(line)
				if after, ok := strings.CutPrefix(line, "module "); ok {
					moduleName := strings.TrimSpace(after)
					rel, relErr := filepath.Rel(dir, pkgAbsPath)
					if relErr != nil {
						return "", relErr
					}
					return moduleName + "/" + filepath.ToSlash(rel), nil
				}
			}
		}
		parent := filepath.Dir(dir)
		if parent == dir {
			break
		}
		dir = parent
	}
	return "", fmt.Errorf("go.mod not found starting from %s", outDir)
}
